import { test, expect } from '@playwright/test'
test('shop, cart persistence, product details, and demo checkout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173')
  await expect(page.getByRole('heading', { name: 'A little further out.' })).toBeVisible()
  await expect(page.locator('.product')).toHaveCount(4)
  await page.getByRole('button', { name: 'Camp & kitchen', exact: true }).click()
  await expect(page.locator('.product')).toHaveCount(1)
  await page.getByRole('button', { name: /All goods/ }).click()
  await page.getByRole('button', { name: 'View The Daybreak Pack' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Add to bag', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Open shopping bag, 1 items' }).click()
  await expect(page.getByText('You’re $12.00 from free shipping.')).toBeVisible()
  await page.getByRole('button', { name: 'Increase The Daybreak Pack quantity' }).click()
  await expect(page.getByText('Good news — shipping is on us.')).toBeVisible()
  await page.getByRole('button', { name: 'Demo checkout' }).click()
  await expect(page.getByText(/You’ve reached the end of the demo/)).toBeVisible()
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Open shopping bag, 2 items' })).toBeVisible()
  await page.getByRole('button', { name: 'Open shopping bag, 2 items' }).click()
  await page.getByRole('button', { name: 'Remove The Daybreak Pack', exact: true }).click()
  await expect(page.getByText('A little room for adventure.')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.locator('#email').fill('explorer@example.com')
  await page.getByRole('button', { name: 'Subscribe to field notes' }).click()
  await expect(page.getByText('You’re on the demo list. See you out there!')).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBeTruthy()
})
test('desktop and mobile layouts', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('http://127.0.0.1:5173')
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Toggle navigation' }).click()
  await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('button', { name: 'Field notes' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
})
